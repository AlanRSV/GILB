SPACE_ADV = 5
CAP = 12                                 # rows above the baseline
NAME, PX, LINE, BASE, UP, DOWN = b'PX\0\0', 12, 20, 15, 12, 3


def glyph(ch):
    """(w, h, left, top, adv, rows) trimmed to the ink box; rows of 0/1."""
    if ch == ' ':
        return 0, 0, 0, 0, SPACE_ADV, []
    first, rows = G[ch]
    width = len(rows[0])
    ink = [(r, c) for r, row in enumerate(rows) for c, v in enumerate(row) if v == '#']
    r0, r1 = min(r for r, _ in ink), max(r for r, _ in ink)
    c0, c1 = min(c for _, c in ink), max(c for _, c in ink)
    out = [[1 if rows[r][c] == '#' else 0 for c in range(c0, c1 + 1)] for r in range(r0, r1 + 1)]
    return c1 - c0 + 1, r1 - r0 + 1, c0, first + r0 - CAP, width + 2, out


def order():
    return [chr(c) for c in range(0x20, 0x7F)] + ['–', '—', '‘', '’', '“', '”', '…', '�']   # (code order)


def check():
    bad = 0
    for ch, (first, rows) in G.items():
        if len({len(r) for r in rows}) != 1:
            print('rows of different widths:', repr(ch), [len(r) for r in rows])
            bad += 1
        if first + len(rows) > 15:
            print('below the descenders:', repr(ch))
            bad += 1
    missing = [c for c in order() if c != ' ' and c not in G]
    if missing:
        print('missing:', missing)
        bad += 1
    print('glyphs', len(G), 'problems', bad)
    return bad


def font_bytes(base):
    """The PX font's header (40 B) and data, its offsets from `base` (where the header goes)."""
    chars = order()
    codes = b''.join(struct.pack('<H', ord(c)) for c in chars)
    codes += b'\0' * (-len(codes) & 3)
    recs, bits = b'', b''
    for c in chars:
        w, h, left, top, adv, rows = glyph(c)
        recs += struct.pack('<HBBbbBB', len(bits), w, h, left, top, adv, 0)
        for row in rows:
            row = row + [0] * (-len(row) & 3)
            for i in range(0, len(row), 4):
                v = 0
                for k in range(4):
                    v = v << 2 | (3 if row[i + k] else 0)
                bits += bytes([v])
    bits += b'\0' * (-len(bits) & 3)
    oc = base + 40
    orr = oc + len(codes)
    ob = orr + len(recs)
    hdr = NAME + bytes([PX, LINE, BASE, 0, UP, DOWN, 1, 0]) + struct.pack(
        '<HH6I', len(chars), len(chars) - 1, oc, orr, ob, 0, 0, len(bits))
    return hdr + codes + recs + bits


def shifted(b, offs, first, end, shift):
    """b[first:end] with the absolute offsets in the headers at offs moved by shift."""
    body = bytearray(b[first:end])
    for o in offs:
        h = o - first
        for f in range(16, 36, 4):                            # codes, recs, bits, shaping, marks
            v = struct.unpack('<I', body[h + f: h + f + 4])[0]
            if v:
                struct.pack_into('<I', body, h + f, v + shift)
    return body


def strip(b):
    """b without PX (the last font: what blob() appends), or b as it is."""
    n = struct.unpack('<I', b[12:16])[0]
    offs = [struct.unpack('<I', b[16 + 4 * i: 20 + 4 * i])[0] for i in range(n)]
    if b[offs[-1]:offs[-1] + 4] != NAME:
        assert all(b[o:o + 4] != NAME for o in offs)
        return b
    keep, first = offs[:-1], min(offs)
    body = shifted(b, keep, first, offs[-1], -4)
    while body and len(body) % 4:
        body.pop()
    total = 16 + 4 * len(keep) + len(body)
    out = bytearray(b'RCFONT2\0' + struct.pack('<II', total, len(keep)))
    for o in keep:
        out += struct.pack('<I', o - 4)
    return bytes(out + body)


def blob(src, dst):
    b = strip(open(src, 'rb').read())                        # (PX there already: replaced)
    assert b[:8] == b'RCFONT2\0'
    n = struct.unpack('<I', b[12:16])[0]
    keep = [struct.unpack('<I', b[16 + 4 * i: 20 + 4 * i])[0] for i in range(n)]
    first = min(keep)
    shift = 4                                                 # one more offset in the table
    body = shifted(b, keep, first, len(b), shift)
    head_len = 16 + 4 * (n + 1)
    assert head_len == first + shift, 'the fonts do not start right after the offset table'
    body += b'\0' * (-len(body) & 3)
    px_at = head_len + len(body)
    px = font_bytes(px_at)
    total = head_len + len(body) + len(px)
    out = bytearray(b'RCFONT2\0' + struct.pack('<II', total, n + 1))
    for o in keep:
        out += struct.pack('<I', o + shift)
    out += struct.pack('<I', px_at)
    out += body + px
    assert len(out) == total
    open(dst, 'wb').write(out)
    print('%s: %d B (PX %d B)' % (dst, total, len(px)))


def c_array(src, dst):
    """fonts_blob.c (the host tests' and the simulator's copy of the blob) from the blob."""
    b = open(src, 'rb').read()
    b += b'\0' * (-len(b) & 3)
    words = struct.unpack('<%dI' % (len(b) // 4), b)
    with open(dst, 'w', newline='\n') as o:
        o.write('/* fonts_blob.c -- the baked fonts: B13 M13 T17 D28 (tools/gen_font.py in the project repo, from\n'
                ' * Noto Sans, Noto Sans Devanagari and Noto Sans Math, SIL OFL 1.1: OFL.txt) and PX (GILB\'s own,\n'
                ' * tools/gilb_pixfont.py); the bytes of rechord_fonts.bin (host tests and the simulator; the\n'
                ' * firmware loads rechord_fonts.bin from its slot). GENERATED by tools/gilb_pixfont.py: do not edit. */\n'
                '#include <stdint.h>\n\n')
        o.write('const uint32_t rechord_fonts_len = %du;\n' % len(open(src, 'rb').read()))
        o.write('const uint32_t rechord_fonts_blob[] __attribute__((aligned(4))) = {\n')
        for i in range(0, len(words), 8):
            o.write('    ' + ' '.join('0x%08X,' % w for w in words[i:i + 8]) + '\n')
        o.write('};\n')
    print('%s: %d words' % (dst, len(words)))


def preview(path, lines):
    W, H, S = 320, 170, 3
    bg, fg = (0xC5, 0xD0, 0xE2), (0x23, 0x31, 0x7F)
    img = [[bg] * W for _ in range(H)]
    def text(x, base, s):
        for ch in s:
            w, h, left, top, adv, rows = glyph(ch if ch == ' ' or ch in G else '�')
            for r, row in enumerate(rows):
                for c, v in enumerate(row):
                    X, Y = x + left + c, base + top + r
                    if v and 0 <= X < W and 0 <= Y < H:
                        img[Y][X] = fg
            x += adv
    for y in range(42, 126):                      # the cover's place
        for x in range(8, 92):
            img[y][x] = fg
    text(8, 37, lines[0])
    for i, s in enumerate(lines[1:5]):
        text(102, 58 + 22 * i, s)
    for x in range(8, 312):
        img[139][x] = img[148][x] = fg
    for y in range(139, 149):
        img[y][8] = img[y][311] = fg
    for y in range(141, 147):
        for x in range(10, 120):
            img[y][x] = fg
    text(8, 167, lines[5])
    text(250, 167, lines[6])
    with open(path, 'wb') as o:
        o.write(b'P6 %d %d 255\n' % (W * S, H * S))
        for row in img:
            line = b''.join(bytes(c) * S for c in row)
            for _ in range(S):
                o.write(line)


